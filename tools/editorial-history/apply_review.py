changed = Counter()
for path in sorted(Path('th').glob('*.json')):
    table = path.stem
    before = json.loads(Path('out/thai-proofread/before', path.name).read_text(encoding='utf-8'))
    direct_edits = edits.get(table, {})
    if table == 'menu.1':
        en = json.loads(Path('source/en', path.name).read_text(encoding='utf-8'))
        ja = json.loads(Path('source/ja', path.name).read_text(encoding='utf-8'))
        copies = {(en[k], ja.get(k), before[k]): v for k, v in direct_edits.items()}
        direct_edits = {k: copies[(en[k], ja.get(k), v)] for k, v in before.items()
                        if (en[k], ja.get(k), v) in copies}
    after = {}
    for key, old in before.items():
        value = direct_edits.get(key, old)
        for previous, current in typos.items():
            value = value.replace(previous, current)
        if table not in {'item.10', 'item.11', 'item.12', 'item.18', 'item.19', 'menu.31'}:
            value = join_term.sub(r'\1', value)
        for previous, current in specialized.get(table, {}).items():
            value = value.replace(previous, current)
        if table == 'menu.2' and len(key) == 7 and key.startswith('103') and key != '1030001':
            value = value.replace('นี่คือโรคภัยแห่ง ', 'นี่คือภัยจาก')
        if value != old:
            changed[table] += 1
        after[key] = value
    if changed[table]:
        raw = Path('out/thai-proofread/before', path.name).read_bytes()
        suffix = '\n' if raw.endswith(b'\n') else ''
        newline = '\r\n' if b'\r\n' in raw else '\n'
        path.write_text(json.dumps(after, ensure_ascii=False, indent=1) + suffix,
                        encoding='utf-8', newline=newline)

